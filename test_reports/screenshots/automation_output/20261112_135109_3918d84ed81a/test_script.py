async def run_test(page, output_dir, page_url):
    import asyncio,json
    from urllib.parse import urlparse,parse_qs
    await page.set_viewport_size({'width':1920,'height':800})
    base=page.url.split('/')[0]+'//'+page.url.split('/')[2]
    results=[]
    try:
        seen=[]
        async def latest(route):
            month=parse_qs(urlparse(route.request.url).query)['month'][0];seen.append(month)
            if month=='2026-07': await asyncio.sleep(1.8)
            try: await route.fulfill(status=200,content_type='application/json',body=json.dumps({'text':'TEST_latest_'+month}))
            except Exception: pass
        await page.route('**/api/diagnostics/latest?*',latest)
        await page.goto(base+'/diagnosticos')
        await page.get_by_test_id('period-select').wait_for(timeout=15000)
        await page.get_by_test_id('period-select').select_option('2026-07')
        await page.get_by_test_id('period-select').wait_for(timeout=15000)
        await page.wait_for_timeout(150)
        await page.get_by_test_id('period-select').select_option('2026-10')
        await page.get_by_test_id('ai-diagnostic-text').filter(has_text='TEST_latest_2026-10').wait_for(timeout=15000)
        await page.wait_for_timeout(2200)
        assert 'TEST_latest_2026-07' not in await page.get_by_test_id('ai-diagnostic-text').inner_text()
        assert '2026-07' in seen
        print('PASS diagnostics latest period ownership')
        results.append({'test':'diagnostics latest ownership','passed':True})
        started=asyncio.Event()
        async def delayed_stream(route):
            started.set();await asyncio.sleep(1.8)
            try: await route.fulfill(status=200,content_type='text/event-stream',body='data: {"text":"TEST_OLD_STREAM"}\n\ndata: {"done":true}\n\n')
            except Exception: pass
        await page.route('**/api/diagnostics/stream?*',delayed_stream)
        await page.get_by_test_id('generate-diagnostic').click(force=True)
        await asyncio.wait_for(started.wait(),timeout=5)
        await page.get_by_test_id('period-select').select_option('2026-07')
        await page.get_by_test_id('period-select').wait_for(timeout=15000)
        await page.wait_for_timeout(2400)
        assert 'TEST_OLD_STREAM' not in await page.get_by_test_id('ai-diagnostic-text').inner_text()
        assert 'Analisando...' not in await page.get_by_test_id('generate-diagnostic').inner_text()
        assert await page.get_by_test_id('generate-diagnostic').is_enabled()
        print('PASS diagnostics pending stream aborted on month change; new button not busy')
        results.append({'test':'diagnostics stream cancellation','passed':True})
        await page.unroute('**/api/diagnostics/stream?*',delayed_stream)
        async def incomplete_stream(route): await route.fulfill(status=200,content_type='text/event-stream',body='data: {"text":"TEST_PARTIAL"}\n\n')
        await page.route('**/api/diagnostics/stream?*',incomplete_stream)
        await page.get_by_test_id('generate-diagnostic').click(force=True)
        await page.get_by_test_id('diagnostic-error').wait_for(timeout=10000)
        assert 'interrompida' in await page.get_by_test_id('diagnostic-error').inner_text()
        assert await page.get_by_test_id('generate-diagnostic').is_enabled()
        print('PASS SSE missing terminal done reported as error')
        results.append({'test':'SSE terminal done','passed':True})
        await page.unroute('**/api/diagnostics/stream?*',incomplete_stream)
        started.clear()
        await page.route('**/api/diagnostics/stream?*',delayed_stream)
        await page.clock.install()
        await page.get_by_test_id('generate-diagnostic').click(force=True)
        await asyncio.wait_for(started.wait(),timeout=5)
        await page.clock.fast_forward(136000)
        await page.get_by_test_id('diagnostic-error').wait_for(timeout=10000)
        assert 'demorou' in await page.get_by_test_id('diagnostic-error').inner_text()
        assert await page.get_by_test_id('generate-diagnostic').is_enabled()
        print('PASS diagnostics 135-second timeout clears busy state (TEST accelerated clock)')
        results.append({'test':'diagnostics timeout','passed':True})
        await page.clock.resume()
        await page.unroute('**/api/diagnostics/stream?*',delayed_stream)
    except Exception as e:
        print('FAIL diagnostics',str(e));results.append({'test':'diagnostics','passed':False,'error':str(e)})
    finally: await page.unroute('**/api/diagnostics/latest?*',latest)
    try:
        async def empty_history(route): await route.fulfill(status=200,content_type='application/json',body='[]')
        started_chat=asyncio.Event()
        async def delayed_chat(route):
            started_chat.set();await asyncio.sleep(1.8)
            try: await route.fulfill(status=200,content_type='text/event-stream',body='data: {"type":"delta","text":"TEST_OLD_ADVISOR"}\n\ndata: {"type":"done"}\n\n')
            except Exception: pass
        await page.route('**/api/advisor/conversations?*',empty_history)
        await page.route('**/api/advisor/chat',delayed_chat)
        await page.goto(base+'/consultor')
        await page.get_by_test_id('advisor-message-input').wait_for(timeout=15000)
        await page.get_by_test_id('advisor-message-input').fill('TEST_pending_old_month')
        await page.get_by_test_id('advisor-send').click(force=True)
        await asyncio.wait_for(started_chat.wait(),timeout=5)
        await page.get_by_test_id('period-select').select_option('2026-07')
        await page.get_by_test_id('advisor-welcome-title').wait_for(timeout=15000)
        await page.wait_for_timeout(2200)
        assert await page.get_by_text('TEST_OLD_ADVISOR',exact=True).count()==0
        assert await page.get_by_test_id('advisor-message-input').is_enabled()
        print('PASS advisor old stream cannot update another month')
        results.append({'test':'advisor stream month ownership','passed':True})
        started_chat.clear()
        await page.get_by_test_id('advisor-message-input').fill('TEST_pending_navigation')
        await page.get_by_test_id('advisor-send').click(force=True)
        await asyncio.wait_for(started_chat.wait(),timeout=5)
        await page.get_by_test_id('nav-overview').click(force=True)
        await page.get_by_test_id('chart-monthly').wait_for(timeout=15000)
        await page.wait_for_timeout(2200)
        await page.get_by_test_id('nav-consultor').click(force=True)
        await page.get_by_test_id('advisor-welcome-title').wait_for(timeout=15000)
        assert await page.get_by_text('TEST_OLD_ADVISOR',exact=True).count()==0
        assert await page.get_by_test_id('advisor-message-input').is_enabled()
        print('PASS navigation aborts advisor stream')
        results.append({'test':'advisor navigation cancellation','passed':True})
    except Exception as e:
        print('FAIL advisor cancellation',str(e));results.append({'test':'advisor cancellation','passed':False,'error':str(e)})
    finally:
        await page.unroute('**/api/advisor/conversations?*',empty_history)
        await page.unroute('**/api/advisor/chat',delayed_chat)
    print('UI_RESULTS',json.dumps(results))
    error_text=await page.evaluate('''() => {const errorElements = Array.from(document.querySelectorAll('.error, [class*="error"], [id*="error"]')); return errorElements.map(el => el.textContent).join(', ');}''')
    print('Found error message: '+error_text if error_text else 'No error messages found on the page')
